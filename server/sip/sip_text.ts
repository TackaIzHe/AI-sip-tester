/** Человекочитаемая расшифровка частых SIP-кодов ответов станции. */
export const SIP_STATUS_TEXT: Record<number, string> = {
    401: 'Станция отвергла аутентификацию — проверьте пароль',
    403: 'Запрещено: проверьте номер и пароль',
    404: 'Абонент не найден',
    407: 'Станция отвергла аутентификацию (proxy)',
    408: 'Тайм-аут: станция не отвечает',
    480: 'Абонент недоступен',
    486: 'Абонент занят',
    487: 'Вызов отменён',
    488: 'Неприемлемые медиа (SDP)',
    503: 'Станция недоступна',
    603: 'Вызов отклонён',
};

/** «486 — Абонент занят» для UI/протокола моста; неизвестный код → «Ошибка SIP N». */
export function sip_status_text(code?: number, fallback = ''): string
{
    if (code && SIP_STATUS_TEXT[code]) return `${code} — ${SIP_STATUS_TEXT[code]}`;
    if (code) return `Ошибка SIP ${code}`;
    return fallback;
}
